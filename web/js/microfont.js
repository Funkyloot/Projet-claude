export function textWidth(s) { return s.length * 4 - 1; }

export function drawText(ctx, s, x, y, color) {
  x = Math.round(x); y = Math.round(y);
  const up = s.toUpperCase();
  for (let i = 0; i < up.length; i++) {
    const g = G[up[i]];
    if (!g) continue;
    for (let r = 0; r < 5; r++) {
      for (let c = 0; c < 3; c++) {
        if (g[r][c] === '#') px(ctx, x + i * 4 + c, y + r, color);
      }
    }
  }
}
